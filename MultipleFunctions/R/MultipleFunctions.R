# Addition
#' @export
add <- function(a, b) {
  return(a + b)
}

# Subtraction
#' @export
subtract <- function(a, b) {
  return(a - b)
}

# Multiplication
#' @export
multiply <- function(a, b) {
  return(a * b)
}

# Division
#' @export
divide <- function(a, b) {
  return(a / b)
}

library(MultipleFunctions)

add(10, 5)
subtract(10, 5)
multiply(10, 5)
divide(10, 5)
